import React, { useState } from 'react';
import { useForm, FormProvider } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { Box, Button, CircularProgress, Grid, Alert, Typography } from '@mui/material';
import SaveIcon from '@mui/icons-material/Save';
import { useNavigate } from 'react-router-dom';

import { customerSchema, type CustomerFormValues } from '../../schemas/customer';
import { FormTextField } from '../form/FormTextField';
import { FormSwitch } from '../form/FormSwitch';
import { SectionCard } from '../common/SectionCard';
import {
  useCreateCustomerMutation,
  useUpdateCustomerMutation,
} from '../../store/api/customersApi';
import { useNotify } from '../../hooks/useNotify';
import { useApiFormErrors } from '../../hooks/useApiFormErrors';
import { ROUTES } from '../../constants/routes';
import { MESSAGES } from '../../constants/messages';
import type { Customer } from '../../types/api/customer';

export interface CustomerFormProps {
  initialData?: Customer;
}

export const CustomerForm: React.FC<CustomerFormProps> = ({ initialData }) => {
  const navigate = useNavigate();
  const { notifySuccess } = useNotify();
  const isEdit = Boolean(initialData);

  const [createCustomer, { isLoading: isCreating }] = useCreateCustomerMutation();
  const [updateCustomer, { isLoading: isUpdating }] = useUpdateCustomerMutation();

  const [submitError, setSubmitError] = useState<string | null>(null);

  const methods = useForm<CustomerFormValues>({
    resolver: zodResolver(customerSchema),
    defaultValues: {
      name: initialData?.name ?? '',
      phone: initialData?.phone ?? '',
      gstin: initialData?.gstin ?? '',
      state: initialData?.state ?? '',
      billing_address: initialData?.billing_address ?? '',
      is_active: initialData?.is_active ?? true,
    },
  });

  const { handleApiFormErrors } = useApiFormErrors(methods.setError);

  const onSubmit = async (values: CustomerFormValues) => {
    setSubmitError(null);
    try {
      if (isEdit && initialData) {
        await updateCustomer({
          id: initialData.id,
          name: values.name,
          phone: values.phone,
          gstin: values.gstin || undefined,
          state: values.state,
          billing_address: values.billing_address,
          is_active: values.is_active,
        }).unwrap();
        notifySuccess(MESSAGES.general.updateSuccess);
        navigate(ROUTES.customers.detail(initialData.id));
      } else {
        const created = await createCustomer({
          name: values.name,
          phone: values.phone,
          gstin: values.gstin || undefined,
          state: values.state,
          billing_address: values.billing_address,
        }).unwrap();
        notifySuccess(MESSAGES.general.createSuccess);
        navigate(ROUTES.customers.detail(created.id));
      }
    } catch (err: unknown) {
      const detail = handleApiFormErrors(err);
      if (detail) {
        setSubmitError(detail);
      }
    }
  };

  const isLoading = isCreating || isUpdating;

  return (
    <SectionCard
      title={isEdit ? `Edit Customer (${initialData?.name})` : 'New Customer Profile'}
      subheader="Customer billing address, phone number, and tax registration credentials."
    >
      {submitError && (
        <Alert severity="error" sx={{ mb: 3 }}>
          {submitError}
        </Alert>
      )}

      <FormProvider {...methods}>
        <Box component="form" onSubmit={methods.handleSubmit(onSubmit)} noValidate>
          {isEdit && initialData && (
            <Box sx={{ mb: 2, p: 1.5, backgroundColor: 'action.hover', borderRadius: 1 }}>
              <Typography variant="caption" color="text.secondary">
                Customer Code (Auto-generated by system):
              </Typography>
              <Typography variant="body2" fontWeight={600}>
                {initialData.code}
              </Typography>
            </Box>
          )}

          <Grid container spacing={2}>
            <Grid item xs={12} sm={6}>
              <FormTextField
                name="name"
                label="Customer / Business Name"
                required
                disabled={isLoading}
                autoFocus
              />
            </Grid>

            <Grid item xs={12} sm={6}>
              <FormTextField
                name="phone"
                label="Phone Number"
                required
                disabled={isLoading}
                placeholder="10 to 15 digits"
              />
            </Grid>

            <Grid item xs={12} sm={6}>
              <FormTextField
                name="gstin"
                label="GSTIN (Optional)"
                placeholder="33ABCDE1234F1Z5"
                disabled={isLoading}
                inputProps={{ style: { textTransform: 'uppercase' } }}
              />
            </Grid>

            <Grid item xs={12} sm={6}>
              <FormTextField
                name="state"
                label="State"
                required
                disabled={isLoading}
                placeholder="e.g. Tamil Nadu"
              />
            </Grid>

            <Grid item xs={12}>
              <FormTextField
                name="billing_address"
                label="Billing Address"
                multiline
                rows={3}
                required
                disabled={isLoading}
              />
            </Grid>

            {isEdit && (
              <Grid item xs={12}>
                <FormSwitch
                  name="is_active"
                  label="Active Account"
                  disabled={isLoading}
                />
              </Grid>
            )}
          </Grid>

          <Box sx={{ mt: 3, display: 'flex', justifyContent: 'flex-end', gap: 2 }}>
            <Button
              variant="outlined"
              color="inherit"
              disabled={isLoading}
              onClick={() => navigate(isEdit && initialData ? ROUTES.customers.detail(initialData.id) : ROUTES.customers.list)}
            >
              Cancel
            </Button>
            <Button
              type="submit"
              variant="contained"
              color="primary"
              disabled={isLoading}
              startIcon={
                isLoading ? <CircularProgress size={16} color="inherit" /> : <SaveIcon />
              }
            >
              {isLoading ? 'Saving...' : isEdit ? 'Save Changes' : 'Create Customer'}
            </Button>
          </Box>
        </Box>
      </FormProvider>
    </SectionCard>
  );
};
